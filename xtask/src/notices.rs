//! 外壳的第三方许可证清单 `THIRD-PARTY-LICENSES.txt`（施工 DT-7，照核心仓库的 `xtask/src/notices.rs`，核心施工 AU-2）：编进
//! 外壳的第三方包，每个的版权和许可证原文，随安装包发（MIT、BSD、Apache 都要求分发时附上）。核心、网页软件各有各的一份，
//! 打包时一起放进去（`packaging/stage.py`）。
//!
//! 取安装包三个平台上从外壳顺着正常依赖走得到的包的并集（开发依赖、构建依赖不编进程序，门禁的小程序自己也不算），每个包读它
//! 源码目录里带的许可证文件；一份都没带的用这里自带的标准原文，版权行写清单里的 `authors`。原文一字不差的合成一段，段前列出
//! 用它的包；MPL-2.0 的包后面写上 crates.io 上它的源码在哪（MPL 第 3.2 条：发编好的程序要告诉人源码从哪拿）。按名字排，
//! 同样的依赖图生成出来一字不差。
//!
//! `cargo xtask notices` 写这份文件；`cargo xtask check` 重算一遍，和仓库里的不一样就算没过。

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::licenses;

/// 这份清单在仓库里的位置。
pub const PATH: &str = "THIRD-PARTY-LICENSES.txt";

/// 门禁的小程序：工作区里有它，但不编进安装包，不从它往下走。
const NOT_SHIPPED: &str = "xtask";

/// 包没带许可证文件时用的标准原文：SPDX 编号和原文，`{authors}` 换成清单里的作者。前三份照核心的；MPL-2.0 是外壳多的：
/// Tauri 带进来的 `selectors`（Servo 的）没带文件，原文照 Mozilla 发的（`option-ext` 带的那份），没有版权行。
const STANDARD: [(&str, &str); 4] = [
    ("MIT", include_str!("notices/MIT.txt")),
    ("Apache-2.0", include_str!("notices/Apache-2.0.txt")),
    ("BSD-3-Clause", include_str!("notices/BSD-3-Clause.txt")),
    ("MPL-2.0", include_str!("notices/MPL-2.0.txt")),
];

/// 文件名照大写比，以这几样开头的是许可证文件。
const NAMES: [&str; 5] = ["LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"];

/// 清单开头的两行。
const HEAD: &str = "Third-party software included in the Miyu desktop shell (miyu-desktop), with the full text of each license.\n\
Generated by `cargo xtask notices` from the dependency graph; do not edit by hand.\n";

/// 分段的线。
const RULE: &str =
    "================================================================================";

/// 编进外壳的一个第三方包。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Shipped {
    pub(crate) name: String,
    pub(crate) version: String,
    /// `license` 的原文，没写的是空的。
    pub(crate) license: Option<String>,
    pub(crate) authors: Vec<String>,
    /// 源码目录：`Cargo.toml` 所在的那一层。
    pub(crate) dir: PathBuf,
    /// 清单里 `license-file` 指的文件，相对源码目录。
    pub(crate) license_file: Option<String>,
}

impl Shipped {
    /// 段前列它的那一行：名字、版本，写了 `license` 的带上；MPL 的再写源码在哪。
    pub(crate) fn label(&self) -> String {
        let mut line = match &self.license {
            Some(license) => format!("{} {} ({license})", self.name, self.version),
            None => format!("{} {}", self.name, self.version),
        };
        if self.license.as_deref().is_some_and(|l| l.contains("MPL")) {
            line.push_str(&format!(
                ", source code: https://crates.io/crates/{}/{}",
                self.name, self.version
            ));
        }
        line
    }
}

/// 写这份清单。
///
/// # Errors
///
/// 生成不了（见 [`render`]）、写不进。
pub fn write(root: &Path, cargo: &str) -> Result<(), String> {
    let text = render(root, cargo)?;
    std::fs::write(root.join(PATH), text).map_err(|e| format!("写不了 {PATH}：{e}"))
}

/// 查：照依赖图生成的，和仓库里的那份一字不差。
pub fn check(root: &Path, cargo: &str) -> Vec<String> {
    let expected = match render(root, cargo) {
        Ok(text) => text,
        Err(e) => return vec![e],
    };
    match std::fs::read_to_string(root.join(PATH)) {
        Ok(actual) if actual == expected => Vec::new(),
        Ok(_) => vec![format!("{PATH} 不是最新的，跑 cargo xtask notices")],
        Err(_) => vec![format!("没有 {PATH}，跑 cargo xtask notices")],
    }
}

/// 照三个平台的依赖图、各包带的许可证文件生成清单。
///
/// # Errors
///
/// `cargo metadata` 跑不了；有包的许可证文件读不了、是空的；有包一份都没带、`license` 里也没有自带原文的那几种。
pub fn render(root: &Path, cargo: &str) -> Result<String, String> {
    let mut all = BTreeMap::new();
    for platform in licenses::PLATFORMS {
        let json = licenses::metadata(root, cargo, platform)
            .map_err(|e| format!("跑不了 cargo metadata（{platform}）：{e}"))?;
        for package in shipped(&json) {
            all.insert((package.name.clone(), package.version.clone()), package);
        }
    }
    let mut groups: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for package in all.values() {
        for text in texts(package)? {
            groups.entry(text).or_default().insert(package.label());
        }
    }
    Ok(page(groups))
}

/// 从 `cargo metadata` 的输出里取：从外壳顺着正常依赖走得到的第三方包。
pub(crate) fn shipped(json: &Value) -> Vec<Shipped> {
    let ids = |value: &Value| -> Vec<String> {
        value
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|item| item.as_str().map(str::to_string))
            .collect()
    };
    let packages: Vec<&Value> = json["packages"].as_array().into_iter().flatten().collect();
    let name_of = |id: &str| -> Option<&str> {
        packages
            .iter()
            .find(|package| package["id"].as_str() == Some(id))
            .and_then(|package| package["name"].as_str())
    };
    let members: BTreeSet<String> = ids(&json["workspace_members"]).into_iter().collect();
    let mut normal: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for node in json["resolve"]["nodes"].as_array().into_iter().flatten() {
        let Some(id) = node["id"].as_str() else {
            continue;
        };
        let deps = node["deps"]
            .as_array()
            .into_iter()
            .flatten()
            .filter(|dep| {
                dep["dep_kinds"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .any(|kind| kind["kind"].is_null())
            })
            .filter_map(|dep| dep["pkg"].as_str().map(str::to_string))
            .collect();
        normal.insert(id.to_string(), deps);
    }
    let mut reached = BTreeSet::new();
    let mut next: Vec<String> = members
        .iter()
        .filter(|id| name_of(id) != Some(NOT_SHIPPED))
        .cloned()
        .collect();
    while let Some(id) = next.pop() {
        if reached.insert(id.clone()) {
            next.extend(normal.get(&id).into_iter().flatten().cloned());
        }
    }
    packages
        .iter()
        .filter(|package| {
            package["id"]
                .as_str()
                .is_some_and(|id| reached.contains(id) && !members.contains(id))
        })
        .map(|package| Shipped {
            name: package["name"].as_str().unwrap_or_default().to_string(),
            version: package["version"].as_str().unwrap_or_default().to_string(),
            license: package["license"].as_str().map(str::to_string),
            authors: ids(&package["authors"]),
            dir: package["manifest_path"]
                .as_str()
                .map(Path::new)
                .and_then(Path::parent)
                .map(Path::to_path_buf)
                .unwrap_or_default(),
            license_file: package["license_file"].as_str().map(str::to_string),
        })
        .collect()
}

/// 一个包的许可证原文：带了文件的照文件，一份都没带的照 [`STANDARD`]。
pub(crate) fn texts(package: &Shipped) -> Result<Vec<String>, String> {
    let head = format!("{} {}", package.name, package.version);
    let unreadable =
        |path: &Path, e: std::io::Error| format!("{head}：读不了 {}：{e}", path.display());
    let mut files = BTreeSet::new();
    let entries = std::fs::read_dir(&package.dir).map_err(|e| unreadable(&package.dir, e))?;
    for entry in entries {
        let entry = entry.map_err(|e| unreadable(&package.dir, e))?;
        let upper = entry.file_name().to_string_lossy().to_uppercase();
        if !NAMES.iter().any(|name| upper.starts_with(name)) {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            for each in std::fs::read_dir(&path).map_err(|e| unreadable(&path, e))? {
                files.insert(each.map_err(|e| unreadable(&path, e))?.path());
            }
        } else {
            files.insert(path);
        }
    }
    if let Some(file) = &package.license_file {
        files.insert(package.dir.join(file));
    }
    if files.is_empty() {
        return standard(package).ok_or_else(|| {
            let license = package.license.as_deref().unwrap_or("没写");
            format!("{head}：没带许可证文件，{license} 也没有自带的原文，要人看过")
        });
    }
    files
        .iter()
        .map(|path| read(path).map_err(|e| format!("{head}：{}：{e}", path.display())))
        .collect()
}

/// 没带许可证文件的包：`license` 里出现的、[`STANDARD`] 有原文的那几种，版权行写作者。一种都没有的是空的。
fn standard(package: &Shipped) -> Option<Vec<String>> {
    let license = package.license.as_deref()?;
    let named: BTreeSet<&str> = license
        .split(|c: char| !(c.is_ascii_alphanumeric() || c == '-' || c == '.'))
        .collect();
    let authors = if package.authors.is_empty() {
        format!("the {} authors", package.name)
    } else {
        package.authors.join(", ")
    };
    let found: Vec<String> = STANDARD
        .iter()
        .filter(|(id, _)| named.contains(id))
        .map(|(_, text)| text.replace("{authors}", &authors).trim_end().to_string())
        .collect();
    (!found.is_empty()).then_some(found)
}

/// 读一份原文：换行统一成 `\n`，去掉末尾的空白；不是 UTF-8 的字节照替换字符读。空的算错。
pub(crate) fn read(path: &Path) -> Result<String, String> {
    let bytes = std::fs::read(path).map_err(|e| e.to_string())?;
    let text = String::from_utf8_lossy(&bytes)
        .replace("\r\n", "\n")
        .trim_end()
        .to_string();
    if text.trim().is_empty() {
        Err("是空的".to_string())
    } else {
        Ok(text)
    }
}

/// 拼成整份：每段先列用它的，再是原文；段照第一个用它的排。
pub(crate) fn page(groups: BTreeMap<String, BTreeSet<String>>) -> String {
    let mut ordered: Vec<(BTreeSet<String>, String)> = groups
        .into_iter()
        .map(|(text, users)| (users, text))
        .collect();
    ordered.sort();
    let mut out = String::from(HEAD);
    for (users, text) in ordered {
        out.push('\n');
        out.push_str(RULE);
        out.push('\n');
        for user in &users {
            out.push_str(user);
            out.push('\n');
        }
        out.push('\n');
        out.push_str(&text);
        out.push('\n');
    }
    out
}

